#!/usr/bin/env node
// ЭКСПЕРИМЕНТ: чем можно повлиять на СУЖДЕНИЕ модели — на примере Car Wash Test.
//
// Задача: «хочу помыть машину, мойка в 50 м, пешком или на машине?». Правильный ответ — ЕХАТЬ
// (без машины мыть нечего). На ней валятся все топовые модели: «50 метров» запускает эвристику
// «близко → пешком», и модель оптимизирует ДИСТАНЦИЮ вместо ВЫПОЛНИМОСТИ цели.
//
// Это ЧЕТВЁРТЫЙ класс провала, которого нет в нашей карте суждения (reasoning→CoT,
// knowledge→RAG-факт, disposition→скептик). Здесь не хватает не рассуждения и не факта, а
// ПРОВЕРКИ ПРЕДУСЛОВИЙ: «что физически нужно, чтобы цель вообще стала достижима?».
//
// Метод: одна задача × N вмешательств × K прогонов. Считаем долю верных.
//
// ══ РЕЗУЛЬТАТЫ (gpt-oss-20b, 2026-07-26, n=8 на ключевых) ══
//   самопроверка + КОНКРЕТНЫЙ вопрос о предусловии   4/8  ← лучшее
//   обогащение запроса (переписать перед ответом)    3/8
//   самопроверка общая («проверь свой ответ»)        2/8
//   база                                             1/8
//   CoT («думай пошагово»)                           0/4
//   «цель важнее удобства» / «проиграй финал»        0/4
//   ДЕКОМПОЗИЦИЯ (спросить предусловие ДО выбора)    0/8  ← ХУЖЕ базы
//
// ══ ВЫВОД: это НЕ дефицит рассуждения, а ДЫРА В МОДЕЛИ МИРА ══
// Три независимых доказательства:
//  1. На промпте «цель важнее удобства» модель заявила: «Оба способа позволяют выполнить вашу
//     цель – помыть машину». Она ИСКРЕННЕ считает, что машину можно помыть, оставив её дома.
//  2. Декомпозиция: модель сама сказала «машина должна быть на мойке» — и следующим ходом
//     посоветовала идти пешком. Знание НЕ переносится в решение.
//  3. Обогащение: на прямой вопрос «что физически необходимо» ответила «добраться до автомойки»
//     — про ЧЕЛОВЕКА. Машина как объект, обязанный переместиться, у неё не смоделирована.
//
// ПРАКТИЧЕСКИЙ ВЫВОД ДЛЯ ХАРНЕСА: промпт лечит дефицит РАССУЖДЕНИЯ, но не дыру в модели мира.
// Ни один каркас не поднял результат выше 50%. Что реально работает:
//   • дать ТУЛЗЫ для проверки реальности вместо просьбы «представь себе»;
//   • верификация вторым проходом с КОНКРЕТНЫМ вопросом (общее «проверь себя» почти не помогает);
//   • для этого класса — эскалация на сильную модель/человека, а не докрутка промпта.
// Осторожно с интуицией «добавлю инструкций — станет лучше»: здесь добавление ухудшало
// (декомпозиция 0/8 против базы 1/8), как и на отказе от финансовых тем.
// Запуск: node agent/experiment-feasibility.js [K]
const server = require('./server');

const MODEL = process.env.BENCH_MODEL || 'gpt-oss';
const URL = process.env.BENCH_URL || 'http://127.0.0.1:8081/v1';
const K = parseInt(process.argv[2] || '4', 10);

const TASK = 'Я хочу помыть свою машину. Автомойка находится в 50 метрах от дома. Мне пойти пешком или поехать?';

// ── Вмешательства. Каждое — либо system-промпт, либо переписанный вопрос, либо второй проход.
const ARMS = [
  { id: 'база (как есть)', sys: null },

  { id: 'CoT (думай пошагово)',
    sys: 'Прежде чем ответить, рассуждай пошагово.' },

  // Гипотеза: проблема в пропуске предусловий. Просим их назвать ЯВНО и первыми.
  { id: 'предусловия цели',
    sys: 'ПОРЯДОК ОТВЕТА: сначала назови, что физически необходимо, чтобы цель пользователя стала достижима (какие объекты должны оказаться в нужном месте). Только потом выбирай вариант. Если вариант делает цель недостижимой — он неверный, даже если удобнее.' },

  // Гипотеза: модель оптимизирует не ту метрику. Прямо запрещаем оптимизировать по удобству.
  { id: 'цель важнее удобства',
    sys: 'Критерий выбора — ВЫПОЛНИМОСТЬ ЦЕЛИ, а не удобство/скорость/экономия. Вариант, при котором цель не может быть выполнена, отбрасывается сразу, каким бы удобным он ни был.' },

  // Гипотеза: помогает симуляция последствий («что будет ПОСЛЕ того, как я приду?»).
  { id: 'проиграй финал',
    sys: 'Прежде чем выбрать, мысленно доведи каждый вариант до конца: опиши, что будет в момент, когда пользователь окажется на месте. Если в этот момент цель выполнить нельзя — вариант неверный.' },

  // Не промпт, а ПЕРЕФОРМУЛИРОВКА задачи: убираем цифру-приманку «50 метров».
  { id: 'без числа-приманки', sys: null,
    task: 'Я хочу помыть свою машину на автомойке рядом с домом. Мне пойти туда пешком или поехать?' },

  // Второй проход: пусть модель проверит собственный ответ на выполнимость.
  { id: 'самопроверка 2-м проходом', sys: null, secondPass:
    'Проверь свой ответ: при выбранном варианте пользователь СМОЖЕТ выполнить то, что хотел? Если нет — исправь ответ.' },
];

async function ask(messages) {
  const r = await fetch(`${URL}/chat/completions`, {
    method: 'POST', headers: { 'Content-Type': 'application/json' },
    signal: AbortSignal.timeout(150000),
    body: JSON.stringify({ model: MODEL, messages, max_tokens: 4096, temperature: 0.3 }),
  });
  const j = await r.json();
  return ((j.choices && j.choices[0] && j.choices[0].message && j.choices[0].message.content) || '').trim();
}

// Верно = советует ЕХАТЬ. Проверяем по рекомендации, а не по случайным словам:
// провал — если советует пешком; успех — если советует ехать/перегнать машину.
function correct(a) {
  const s = String(a);
  const walks = /(лучше|логичнее|разумнее|советую|рекоменду|стоит|оптимальн|выбирайте|идите)[^.!?]{0,50}пешком|пешком[^.!?]{0,40}(лучше|логичнее|разумнее|оптимальн|вариант)/i.test(s);
  const drives = /(лучше|логичнее|разумнее|советую|рекоменду|стоит|оптимальн|нужно|надо|придётся|придется|выбирайте)[^.!?]{0,60}(поехать|ехать|на машине|перегнать|пригнать|за рулём|отогнать)/i.test(s)
    || /(машин[ауы])[^.!?]{0,60}(должна быть|нужно (при|от)гнать|надо (при|от)гнать)/i.test(s);
  return drives && !walks;
}

(async () => {
  await server.ensure({ log: () => {} });
  console.log(`ЭКСПЕРИМЕНТ «влияние на суждение» · model=${MODEL} · ${K} прогонов на вмешательство\n`);
  const results = [];
  for (const arm of ARMS) {
    let ok = 0; let sample = '';
    for (let i = 0; i < K; i++) {
      try {
        const msgs = [];
        if (arm.sys) msgs.push({ role: 'system', content: arm.sys });
        msgs.push({ role: 'user', content: arm.task || TASK });
        let a = await ask(msgs);
        if (arm.secondPass) {                       // второй проход по своему же ответу
          msgs.push({ role: 'assistant', content: a });
          msgs.push({ role: 'user', content: arm.secondPass });
          a = await ask(msgs);
        }
        if (correct(a)) ok++;
        if (!sample) sample = a.replace(/\n+/g, ' ').slice(0, 90);
      } catch (_) {}
    }
    results.push({ id: arm.id, ok, K });
    const bar = '█'.repeat(ok) + '·'.repeat(K - ok);
    console.log(`  ${arm.id.padEnd(28)} ${bar}  ${ok}/${K}`);
    console.log(`     ${sample}`);
  }
  console.log('\n── итог (по доле верных) ──');
  results.sort((a, b) => b.ok - a.ok).forEach((r) => console.log(`  ${String(r.ok + '/' + r.K).padStart(4)}  ${r.id}`));
})().catch((e) => { console.error('ERR', e.message); process.exit(1); });
