// ЦЕЛОСТНОСТЬ СООБЩЕНИЯ ШИНЫ: маркер в НАЧАЛЕ, проверяемый получателем по тому, что он реально увидел.
//
// ЗАЧЕМ (владелец, 03.08.2026). Транспорт шины исправен: в логе сообщения лежат целиком (замерено —
// 6519 / 5600 / 4310 знаков, ни персистер, ни отправка ничего не режут). Режется ПОКАЗ — уведомление
// в контекст агента обрывается на длинных сообщениях. desktop-tt4i69c ответил на первый абзац моего
// broadcast и не увидел остальных, а узнали мы об этом только потому, что он сказал вслух.
//
// ЧЕМ ЭТОТ СБОЙ ХУЖЕ ПРЕДЫДУЩИХ: он ЧАСТИЧНЫЙ. «Пусто» заметно. Обрезок — нет: он читается как целое
// сообщение, получатель отвечает на половину вопроса и не подозревает об этом. Ни отправитель, ни
// получатель не получают никакого сигнала.
//
// ПОЧЕМУ МАРКЕР ИМЕННО В НАЧАЛЕ: обрезается ХВОСТ. Контрольная сумма в конце пропала бы вместе с той
// частью, ради которой она нужна. В начале она переживает обрыв и позволяет получателю сказать точно:
// «я вижу 500 знаков из 5601, это фрагмент».
//
// ПОЧЕМУ НЕ ХВАТАЕТ ПОДПИСИ. Подпись (keys.sign) проверяется на приёме, ДО записи в лог, где текст ещё
// целый — она пройдёт зелёной и на обрезанном показе. Проверять обязан САМ АГЕНТ по тому, что дошло
// до его глаз. Это разные звенья цепи: подпись отвечает «от кого», маркер — «всё ли я вижу».
//
// ФОРМАТ: ⟦bi1:<6 hex>:<длина в кодовых точках>⟧ + пробел + тело.
//   • версия bi1 — чтобы смена формата не ломала разбор у старых узлов;
//   • узлы БЕЗ поддержки просто увидят маркер как текст: обратная совместимость не нарушена;
//   • длина рядом с хешем не роскошь — она сразу говорит, СКОЛЬКО потеряно, а не только «не сошлось».
//
// ⚠️ КОЛЛИЗИЯ С ТЕЛОМ. Разбираем маркер ТОЛЬКО в позиции 0 и ТОЛЬКО по строгому шаблону. Текст,
// начинающийся с похожих символов, не может быть принят за маркер (у нас уже была такая беда —
// маркер-стрелка встретился в теле сообщения). Двойная штамповка тоже исключена: stamp() на уже
// помеченном тексте не ставит второй маркер.

const crypto = require('crypto');

const VERSION = 'bi1';
const RE = /^⟦bi1:([0-9a-f]{6}):(\d+)⟧ /;

// Длина в КОДОВЫХ ТОЧКАХ, а не в единицах UTF-16: у нас кириллица и эмодзи, и '📨'.length === 2.
// Считать иначе значило бы, что «длина не сошлась» ложно срабатывает на исправном сообщении.
const clen = (s) => Array.from(String(s)).length;

const digest = (body) => crypto.createHash('sha256').update(String(body), 'utf8').digest('hex').slice(0, 6);

/** Пометить текст. Уже помеченный возвращается как есть — двойная штамповка сломала бы проверку. */
function stamp(text) {
  const s = String(text);
  if (RE.test(s)) return s;
  return `⟦${VERSION}:${digest(s)}:${clen(s)}⟧ ${s}`;
}

/**
 * Проверить полученное. Возвращает ФАКТЫ, а не приговор — решение принимает вызывающий.
 *   stamped   — есть ли маркер вообще (сообщение от узла без поддержки → false, это НЕ ошибка)
 *   ok        — тело сошлось с объявленным хешем
 *   truncated — тело КОРОЧЕ объявленного: почти всегда обрыв показа
 *   body      — тело без маркера (с ним и работать)
 */
function verify(received) {
  const s = String(received == null ? '' : received);
  const m = s.match(RE);
  if (!m) return { stamped: false, ok: null, truncated: null, body: s, reason: 'маркера нет — узел-отправитель его не ставит' };

  const declaredHash = m[1];
  const declaredLen = Number(m[2]);
  const body = s.slice(m[0].length);
  const actualLen = clen(body);
  const actualHash = digest(body);

  // ДВА НЕЗАВИСИМЫХ ПРИЗНАКА, И ОБА ОБЯЗАТЕЛЬНЫ. Первая версия возвращала «целое» по одному лишь
  // совпадению хеша, вообще не глядя на длину, — и мутационный прогон это вскрыл: стоило хешу
  // считаться по подрезанному телу, как обрезанное сообщение проходило за целое, потому что до
  // проверки длины исполнение просто не доходило. Одна проверка, отключив которую ничего не ломается,
  // — это не проверка. Хеш ловит подмену, длина ловит потерю; полагаться на пересечение нельзя.
  if (actualHash === declaredHash && actualLen === declaredLen) {
    return { stamped: true, ok: true, truncated: false, body, declaredLen, actualLen, declaredHash, actualHash,
             reason: '' };
  }
  if (actualHash === declaredHash) {
    // Хеш сошёлся, длина — нет. Либо коллизия 6 hex (1 к 16.7 млн), либо хеш считается не по тому
    // телу, что измеряется. Оба случая означают «проверке верить нельзя», а не «всё хорошо».
    return { stamped: true, ok: false, truncated: actualLen < declaredLen, body, declaredLen, actualLen,
             declaredHash, actualHash,
             reason: `ПРОВЕРКЕ НЕЛЬЗЯ ВЕРИТЬ: хеш совпал, а длина нет (${actualLen} против ${declaredLen}) — считаются разные вещи` };
  }
  // Хеш не сошёлся. РАЗЛИЧАЕМ ДВА РАЗНЫХ ДИАГНОЗА — иначе «повреждено» скроет обычный обрыв показа,
  // и чинить пойдут канал вместо длины сообщения.
  if (actualLen < declaredLen) {
    return { stamped: true, ok: false, truncated: true, body, declaredLen, actualLen, declaredHash, actualHash,
             reason: `ОБРЕЗАНО: видно ${actualLen} знаков из ${declaredLen} (потеряно ${declaredLen - actualLen}). Полный текст — в ~/.agent-bus/<id>.log` };
  }
  return { stamped: true, ok: false, truncated: false, body, declaredLen, actualLen, declaredHash, actualHash,
           reason: `ПОВРЕЖДЕНО: длина сошлась (${actualLen}), хеш нет (${actualHash} вместо ${declaredHash})` };
}

module.exports = { stamp, verify, digest, clen, VERSION, RE };
