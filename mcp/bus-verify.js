#!/usr/bin/env node
// ПРОВЕРКА ТОГО, ЧТО ДОШЛО ДО ГЛАЗ. Скорми сюда текст сообщения ровно в том виде, в каком ты его
// увидел, — инструмент скажет, целое оно или фрагмент.
//
//   node mcp/bus-verify.js <<'EOF'
//   ⟦bi1:a3f9c1:5601⟧ текст...
//   EOF
//
// Коды возврата РАЗДЕЛЕНЫ по смыслу, потому что «не сошлось» и «не смог проверить» требуют разных
// действий, а один код заставил бы вызывающего гадать:
//   0 — целое (или маркера нет: отправитель его не ставит, проверять нечего);
//   1 — ОБРЕЗАНО или ПОВРЕЖДЕНО (иди в лог за полным текстом);
//   2 — не смог прочитать вход.
//
// ЗАЧЕМ ОТДЕЛЬНО ОТ ПОДПИСИ: подпись проверяется на приёме, до записи в лог, где текст ещё целый.
// Обрыв происходит ПОЗЖЕ, при показе, и подпись его не видит. Проверять обязан тот, кто читает.

const { verify } = require('./bus-integrity');

let buf = '';
process.stdin.setEncoding('utf8');
process.stdin.on('data', (d) => { buf += d; });
process.stdin.on('error', () => { console.error('не смог прочитать stdin'); process.exit(2); });
process.stdin.on('end', () => {
  // ⚠️ НЕ trim() целиком: ведущие пробелы — часть тела и влияют на хеш. Срезаем только перевод
  // строки, который добавляет сам heredoc/пайп, иначе исправное сообщение объявлялось бы битым.
  const text = buf.replace(/\r?\n$/, '');
  if (!text) { console.error('пустой вход — проверять нечего'); process.exit(2); }

  const r = verify(text);
  if (!r.stamped) {
    console.log('· маркера нет: отправитель его не ставит (старый узел) — целостность не проверяема');
    process.exit(0);
  }
  if (r.ok) {
    console.log(`✓ ЦЕЛОЕ: ${r.actualLen} знаков, хеш ${r.actualHash} сошёлся`);
    process.exit(0);
  }
  console.error(`✗ ${r.reason}`);
  if (r.truncated) {
    console.error(`  видно ${r.actualLen} из ${r.declaredLen} — ты читаешь ФРАГМЕНТ.`);
    console.error('  НЕ отвечай по нему и НЕ переспрашивай отправителя: полный текст лежит у тебя же.');
    console.error("  grep -n '⟦bi1:" + r.declaredHash + "' ~/.agent-bus/<свой-id>.log");
  }
  process.exit(1);
});
