// ── 5. МНОГОСТРОЧНОЕ: у нас это отдельный больной путь (см. c82b450) ──
test('многострочное с пустыми строками проходит целиком и ловится при обрыве', () => {
  const body = 'первый абзац\n\nвторой абзац\n\nтретий';
  assert.equal(verify(stamp(body)).ok, true);
  const cut = stamp(body).slice(0, 30);
  assert.equal(verify(cut).truncated, true, 'обрыв многострочного тоже опознаётся');
});
