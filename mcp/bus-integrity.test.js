// ТЕСТЫ МАРКЕРА ЦЕЛОСТНОСТИ. Проверяем не «функция что-то вернула», а ЗАЯВЛЕННОЕ СВОЙСТВО:
// получатель, видящий фрагмент, обязан узнать об этом сам, без подсказки отправителя.
//
// Каждый сценарий имеет ЗАРАНЕЕ ИЗВЕСТНЫЙ ОТВЕТ, и есть отдельная проверка на ложное срабатывание:
// валидатор, который кричит всегда, бесполезен ровно так же, как молчащий.
const { test } = require('node:test');
const assert = require('node:assert/strict');
const { stamp, verify, clen, RE } = require('./bus-integrity');

const LONG = 'СРОЧНО: ' + 'важный текст с кириллицей и эмодзи 📨 '.repeat(120);

// ── 1. Исправный путь ──
test('целое сообщение проходит проверку', () => {
  const r = verify(stamp('привет, флот'));
  assert.equal(r.stamped, true);
  assert.equal(r.ok, true);
  assert.equal(r.truncated, false);
  assert.equal(r.body, 'привет, флот', 'тело возвращается без маркера');
});

test('маркер стоит В НАЧАЛЕ — иначе он не переживёт обрыв хвоста', () => {
  const s = stamp('текст');
  assert.match(s, RE, 'маркер в позиции 0');
  assert.equal(s.indexOf('⟦'), 0);
});

test('длина считается в КОДОВЫХ ТОЧКАХ, а не в единицах UTF-16', () => {
  // '📨'.length === 2, но это ОДИН знак. Считать иначе — ложное «длина не сошлась» на исправном.
  const body = '📨📨📨';
  const r = verify(stamp(body));
  assert.equal(r.ok, true);
  assert.equal(r.declaredLen, 3, 'три эмодзи = три знака, а не шесть');
  assert.equal(clen(body), 3);
});

// ── 2. ГЛАВНЫЙ СЦЕНАРИЙ: ровно тот сбой, ради которого всё написано ──
test('ОБРЕЗАННОЕ сообщение опознаётся как фрагмент, а не как целое', () => {
  const full = stamp(LONG);
  const seen = full.slice(0, 500);            // ровно то, что делает показ: рубит хвост
  const r = verify(seen);
  assert.equal(r.stamped, true, 'маркер пережил обрыв — он был первым');
  assert.equal(r.ok, false);
  assert.equal(r.truncated, true, 'диагноз именно ОБРЕЗАНО, а не ПОВРЕЖДЕНО');
  assert.ok(r.actualLen < r.declaredLen);
  assert.match(r.reason, /ОБРЕЗАНО/);
  assert.match(r.reason, new RegExp(String(r.declaredLen)), 'сказано, сколько знаков должно быть');
});

test('обрыв на ЛЮБОЙ длине опознаётся — не только на удобной', () => {
  const full = stamp(LONG);
  const total = clen(full);
  let missed = 0;
  for (let cut = 40; cut < total; cut += 37) {
    const r = verify(Array.from(full).slice(0, cut).join(''));
    if (!(r.stamped && r.ok === false && r.truncated)) missed++;
  }
  assert.equal(missed, 0, 'ни один обрыв не должен пройти как целое сообщение');
});

// ── 3. ПОВРЕЖДЕНИЕ ≠ ОБРЕЗКА: разные причины требуют разных действий ──
test('подмена знака при той же длине = ПОВРЕЖДЕНО, а не обрезано', () => {
  const s = stamp('атака на рассвете');
  const broken = s.replace('рассвете', 'закате!!!');   // та же длина тела
  const r = verify(broken);
  assert.equal(r.ok, false);
  assert.equal(r.truncated, false, 'длина сошлась → это НЕ обрыв показа');
  assert.match(r.reason, /ПОВРЕЖДЕНО/);
});

// ── 4. ЛОЖНЫХ СРАБАТЫВАНИЙ БЫТЬ НЕ ДОЛЖНО ──
test('сообщение БЕЗ маркера не объявляется битым (обратная совместимость)', () => {
  const r = verify('обычный текст со старого узла');
  assert.equal(r.stamped, false);
  assert.equal(r.ok, null, 'не «плохо», а «нечего проверять» — это разные ответы');
  assert.equal(r.body, 'обычный текст со старого узла');
});

test('текст, ПОХОЖИЙ на маркер, не принимается за маркер', () => {
  // У нас уже был баг с коллизией маркера и тела. Шаблон строгий: только позиция 0 и точная форма.
  for (const fake of ['⟦bi1:XYZ:12⟧ тело', '⟦bi9:aaaaaa:5⟧ тело', 'пре ⟦bi1:aaaaaa:5⟧ тело', '⟦bi1:aaaaaa⟧ тело']) {
    assert.equal(verify(fake).stamped, false, `не должно разбираться как маркер: ${fake}`);
  }
});

test('двойная штамповка невозможна — иначе проверка сломалась бы на исправном', () => {
  const once = stamp('текст');
  assert.equal(stamp(once), once, 'повторный stamp ничего не меняет');
  assert.equal(verify(stamp(once)).ok, true);
});

test('пустое тело — законный случай, а не ошибка', () => {
  const r = verify(stamp(''));
  assert.equal(r.ok, true);
  assert.equal(r.declaredLen, 0);
});

test('ведущие и хвостовые пробелы тела сохраняются и входят в хеш', () => {
  const body = '  отступ значим  ';
  const r = verify(stamp(body));
  assert.equal(r.ok, true);
  assert.equal(r.body, body, 'тело не подрезано — иначе хеш не сошёлся бы у получателя');
});

// ── 4-бис. ДВА ПРИЗНАКА НЕЗАВИСИМЫ: ни один не должен быть единственным ──
// Поймано мутацией 03.08.2026: verify возвращал «целое» по одному совпадению хеша, не проверив
// длину, — и обрезанное проходило за целое, стоило хешу считаться по подрезанному телу.
test('совпадение хеша БЕЗ совпадения длины не считается целым сообщением', () => {
  const s = stamp('тело');
  const declared = s.match(RE);
  // Собираем заведомо противоречивый случай: хеш от тела, а длина объявлена другая.
  const forged = `⟦bi1:${declared[1]}:999⟧ тело`;
  const r = verify(forged);
  assert.equal(r.ok, false, 'длина обязана проверяться независимо от хеша');
  assert.match(r.reason, /ПРОВЕРКЕ НЕЛЬЗЯ ВЕРИТЬ/);
});

test('срез РОВНО хвостовых пробелов тоже опознаётся — это ловит длина, а не хеш', () => {
  // Состязательный случай: обрыв съедает только пробелы. Хеш, посчитанный по подрезанному телу,
  // тут совпал бы — ловит именно независимая проверка длины. Ради этого она и добавлена.
  const body = 'текст с хвостовыми пробелами   ';
  const full = stamp(body);
  const r = verify(full.slice(0, full.length - 3));
  assert.equal(r.ok, false, 'потеря хвостовых пробелов — тоже потеря');
  assert.equal(r.truncated, true);
});

